/**
 * Hot-exit backup records.
 *
 * A dirty editor buffer is written to `<userData>/editor-backups/<tabId>.json`
 * on a debounce. On the next launch the editor tab is still in the persisted tab
 * table, so it reads its backup back and restores the unsaved text.
 *
 * The record is validated on read as well as on write: backup files live in
 * userData and a hand-edited or truncated file must not crash the editor. The
 * tab id is the only filename component, so it is restricted to a safe alphabet
 * and never contains a path separator.
 */

import {
  MAX_BACKUP_AGE_MS,
  MAX_BACKUP_BYTES,
  isWorkspaceRelativePath,
  type EditorBackup,
  type FileEol,
} from "../shared/workspace";

export const BACKUP_VERSION = 1 as const;
export const BACKUP_FILE_SUFFIX = ".json";

const TAB_ID_PATTERN = /^[A-Za-z0-9_-]{1,80}$/;

/** Tab ids are generated by main, but backups are read from disk: validate. */
export function isSafeBackupTabId(value: unknown): value is string {
  return typeof value === "string" && TAB_ID_PATTERN.test(value);
}

/** The only filename a backup may use. */
export function backupFileName(tabId: string): string {
  if (!isSafeBackupTabId(tabId)) {
    throw new Error("invalid backup tab id");
  }
  return `${tabId}${BACKUP_FILE_SUFFIX}`;
}

function byteLength(value: string): number {
  return new TextEncoder().encode(value).byteLength;
}

function isEol(value: unknown): value is FileEol {
  return value === "lf" || value === "crlf";
}

/** Coerces an untrusted backup record into a usable one, or null. */
export function sanitizeEditorBackup(value: unknown): EditorBackup | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  const source = value as Record<string, unknown>;
  if (source.version !== BACKUP_VERSION) return null;
  if (!isSafeBackupTabId(source.tabId)) return null;
  if (typeof source.projectPath !== "string" || source.projectPath.length === 0) return null;
  if (!isWorkspaceRelativePath(source.path)) return null;
  if (typeof source.text !== "string") return null;
  if (byteLength(source.text) > MAX_BACKUP_BYTES) return null;
  if (typeof source.updatedAt !== "number" || !Number.isFinite(source.updatedAt)) return null;
  if (
    source.baselineMtimeMs !== null &&
    (typeof source.baselineMtimeMs !== "number" || !Number.isFinite(source.baselineMtimeMs))
  ) {
    return null;
  }
  if (!isEol(source.eol)) return null;
  return {
    version: BACKUP_VERSION,
    tabId: source.tabId,
    projectPath: source.projectPath,
    path: source.path,
    text: source.text,
    updatedAt: Math.floor(source.updatedAt),
    baselineMtimeMs: source.baselineMtimeMs as number | null,
    eol: source.eol,
    bom: source.bom === true,
  };
}

/** Serializes a backup, or null when the record would exceed the file cap. */
export function serializeEditorBackup(backup: EditorBackup): string | null {
  const sanitized = sanitizeEditorBackup(backup);
  if (!sanitized) return null;
  const json = JSON.stringify(sanitized);
  return byteLength(json) > MAX_BACKUP_BYTES ? null : json;
}

/** Parses a backup file; malformed JSON is a null, never a throw. */
export function parseEditorBackup(text: string | null): EditorBackup | null {
  if (text === null) return null;
  try {
    return sanitizeEditorBackup(JSON.parse(text) as unknown);
  } catch {
    return null;
  }
}

/** True when a backup is older than the retention window. */
export function isEditorBackupExpired(
  backup: EditorBackup,
  now: number,
  maxAgeMs: number = MAX_BACKUP_AGE_MS,
): boolean {
  return now - backup.updatedAt > maxAgeMs;
}
