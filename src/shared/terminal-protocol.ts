/**
 * The terminal wire contract (2026-11-05 native-terminal plan, step 1).
 *
 * A terminal is **not** a Pi session: it has no agent, model or transcript, and
 * it is not a `HOST_METHODS` address. It is a PTY owned by a separate host
 * process (`out/host/terminal.mjs`), addressed by a terminal id and multiplexed
 * per window. Keeping the frames in `src/shared` means the host dispatcher, the
 * main-side supervisor and the renderer event pump agree on one shape.
 *
 * Payload rule: PTY output is arbitrary bytes, so a chunk travels base64-encoded
 * and is handed to xterm as a `Uint8Array`. xterm owns the UTF-8 decoder, which
 * is what makes a multi-byte character split across two chunks safe. Base64's
 * 33 % overhead is bounded by the credit-based flow control below: the host
 * pauses the PTY at `TERMINAL_HIGH_WATER_BYTES` unacked and resumes at
 * `TERMINAL_LOW_WATER_BYTES`.
 */

export const TERMINAL_PROTOCOL_VERSION = 1;

/** Longest accepted `terminal.write` string, measured in UTF-8 bytes. */
export const MAX_TERMINAL_INPUT_BYTES = 1024 * 1024;
/**
 * Frame cap for the terminal host. Larger than the input cap on purpose: JSON
 * escaping can expand a 1 MiB UTF-8 string, and an output batch is base64.
 */
export const MAX_TERMINAL_FRAME_BYTES = 5 * 1024 * 1024;

/** Output is coalesced until either this many bytes or this much time elapses. */
export const TERMINAL_OUTPUT_BATCH_BYTES = 32 * 1024;
export const TERMINAL_OUTPUT_BATCH_MS = 16;

/** Flow control: pause the PTY at the high-water mark, resume at the low one. */
export const TERMINAL_HIGH_WATER_BYTES = 1024 * 1024;
export const TERMINAL_LOW_WATER_BYTES = 256 * 1024;

/** Bytes kept per terminal for a reattach replay (renderer reload / remount). */
export const TERMINAL_REPLAY_BYTES = 256 * 1024;

/** How long a closing terminal may take to exit before it is force-killed. */
export const TERMINAL_CLOSE_GRACE_MS = 2000;

/** Per-window ceiling: a terminal is a process, not a view. */
export const MAX_TERMINALS_PER_WINDOW = 12;

export const MIN_TERMINAL_COLS = 1;
export const MAX_TERMINAL_COLS = 500;
export const MIN_TERMINAL_ROWS = 1;
export const MAX_TERMINAL_ROWS = 300;

export const MAX_TERMINAL_TITLE_LENGTH = 200;
export const MAX_TERMINAL_CWD_LENGTH = 4096;
export const MAX_TERMINAL_ARGV = 64;
export const MAX_TERMINAL_ENV_ENTRIES = 256;
export const MAX_TERMINAL_ENV_VALUE_LENGTH = 32 * 1024;

/** Terminal ids are generated by the host; this is the shape main/UI may echo. */
const TERMINAL_ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/;

/**
 * A usable environment-variable name. Windows legitimately has names such as
 * `ProgramFiles(x86)` and `CommonProgramFiles(x86)`, so the conservative
 * POSIX-style identifier rule would reject a perfectly normal process env. What
 * matters for safety is that the name cannot smuggle a NUL, a newline or an
 * assignment (`=`).
 */
function isEnvName(value: unknown): value is string {
  return (
    typeof value === "string" &&
    value.length > 0 &&
    value.length <= 256 &&
    !value.includes("\0") &&
    !value.includes("=") &&
    !value.includes("\n") &&
    !value.includes("\r")
  );
}

export type TerminalErrorCode =
  "bad_request" | "limit" | "not_found" | "spawn_failed" | "protocol" | "closed";

/** The request methods the terminal host implements. One allowlist, one place. */
export const TERMINAL_METHODS = [
  "terminal.open",
  "terminal.attach",
  "terminal.write",
  "terminal.resize",
  "terminal.close",
  "terminal.ack",
  "terminal.list",
] as const;

export type TerminalMethod = (typeof TERMINAL_METHODS)[number];

export function isTerminalMethod(value: unknown): value is TerminalMethod {
  return typeof value === "string" && (TERMINAL_METHODS as readonly string[]).includes(value);
}

export function isTerminalId(value: unknown): value is string {
  return typeof value === "string" && TERMINAL_ID_PATTERN.test(value);
}

/**
 * How main asks the host to fork a shell. The renderer never builds this: it
 * names a tab, and main resolves the profile, shell path, args and environment.
 */
export interface TerminalSpawnSpec {
  /** Absolute working directory to start the shell in. */
  cwd: string;
  /** Absolute executable path; main resolved and validated it. */
  shell: string;
  args: string[];
  env: Record<string, string>;
  cols: number;
  rows: number;
  /** `TERM` name handed to the PTY (`xterm-256color` by default). */
  name: string;
}

export interface TerminalInfo {
  id: string;
  pid: number;
  /** Present once the shell reports one; defaults to the profile label. */
  title: string;
  cwd: string;
  cols: number;
  rows: number;
}

export interface TerminalOpenParams {
  spec: TerminalSpawnSpec;
}

/** Reattach to a live terminal after a renderer reload or a pane remount. */
export interface TerminalAttachParams {
  terminalId: string;
}

/** The ring-buffer snapshot to replay before live frames resume. */
export interface TerminalAttachResult {
  /** Base64 of the buffered bytes; empty when the terminal produced none. */
  data: string;
  bytes: number;
  /** The last sequence number emitted; live frames continue above it. */
  seq: number;
}

export interface TerminalWriteParams {
  terminalId: string;
  data: string;
}

export interface TerminalResizeParams {
  terminalId: string;
  cols: number;
  rows: number;
}

export interface TerminalCloseParams {
  terminalId: string;
  /** Skip the grace period (host shutdown, tab force-close). */
  force?: boolean;
}

export interface TerminalAckParams {
  terminalId: string;
  /** UTF-8 bytes the renderer has parsed and drawn. */
  bytes: number;
}

export interface TerminalRequestFrame {
  id: number;
  method: TerminalMethod;
  params?: unknown;
}

export interface TerminalFrameError {
  code: TerminalErrorCode;
  message: string;
}

export interface TerminalResponseFrame {
  id: number;
  result?: unknown;
  error?: TerminalFrameError;
}

/** Output chunk: `data` is base64 of exactly `bytes` bytes. */
export interface TerminalDataEvent {
  terminalId: string;
  seq: number;
  data: string;
  bytes: number;
}

export interface TerminalExitEvent {
  terminalId: string;
  exitCode: number;
  signal?: number;
}

export interface TerminalErrorEvent {
  /** Null when the failure is not tied to one terminal (e.g. host protocol). */
  terminalId: string | null;
  code: TerminalErrorCode;
  message: string;
}

export type TerminalEventName = "terminal.data" | "terminal.exit" | "terminal.error";

/** Events carry no request id; they are routed by `terminalId`. */
export interface TerminalEventFrame {
  event: TerminalEventName;
  payload?: unknown;
}

export type TerminalFrame = TerminalRequestFrame | TerminalResponseFrame | TerminalEventFrame;

/** JSONL, one frame per line — the same discipline as the Pi host protocol. */
export function encodeTerminalFrame(frame: TerminalFrame): string {
  return `${JSON.stringify(frame)}\n`;
}

/**
 * Decodes one line. Returns null for blank lines, non-objects, arrays and a
 * frame that is neither a request, a response nor an event. An unknown *method*
 * is intentionally returned so the dispatcher can answer `bad_request` instead
 * of silently dropping the request.
 */
export function decodeTerminalFrame(line: string): TerminalFrame | null {
  if (line.length === 0) return null;
  let value: unknown;
  try {
    value = JSON.parse(line);
  } catch {
    return null;
  }
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  const record = value as Record<string, unknown>;
  const hasId = typeof record.id === "number" && Number.isInteger(record.id) && record.id >= 0;
  if (hasId && typeof record.method === "string") {
    return {
      id: record.id as number,
      method: record.method as TerminalMethod,
      params: record.params,
    };
  }
  if (hasId && ("result" in record || "error" in record)) {
    const frame: TerminalResponseFrame = {
      id: record.id as number,
      result: record.result,
    };
    const error = record.error;
    if (error && typeof error === "object") frame.error = error as TerminalFrameError;
    return frame;
  }
  if (typeof record.event === "string") {
    return {
      event: record.event as TerminalEventName,
      payload: record.payload,
    };
  }
  return null;
}

/** UTF-8 length of a write payload; the cap is bytes, not UTF-16 code units. */
export function terminalInputBytes(text: string): number {
  return new TextEncoder().encode(text).length;
}

export function isTerminalSize(cols: unknown, rows: unknown): boolean {
  return (
    typeof cols === "number" &&
    Number.isInteger(cols) &&
    cols >= MIN_TERMINAL_COLS &&
    cols <= MAX_TERMINAL_COLS &&
    typeof rows === "number" &&
    Number.isInteger(rows) &&
    rows >= MIN_TERMINAL_ROWS &&
    rows <= MAX_TERMINAL_ROWS
  );
}

function isBoundedString(value: unknown, max: number): value is string {
  return (
    typeof value === "string" && value.length > 0 && value.length <= max && !value.includes("\0")
  );
}

/** Validates an untrusted spawn spec before the host forks anything. */
export function isValidTerminalSpawnSpec(value: unknown): value is TerminalSpawnSpec {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  const spec = value as Record<string, unknown>;
  if (!isBoundedString(spec.cwd, MAX_TERMINAL_CWD_LENGTH)) return false;
  if (!isBoundedString(spec.shell, MAX_TERMINAL_CWD_LENGTH)) return false;
  if (!isBoundedString(spec.name, 64)) return false;
  if (!isTerminalSize(spec.cols, spec.rows)) return false;
  if (!Array.isArray(spec.args) || spec.args.length > MAX_TERMINAL_ARGV) return false;
  if (!spec.args.every((arg) => isBoundedString(arg, MAX_TERMINAL_CWD_LENGTH))) return false;
  if (!spec.env || typeof spec.env !== "object" || Array.isArray(spec.env)) return false;
  const entries = Object.entries(spec.env as Record<string, unknown>);
  if (entries.length > MAX_TERMINAL_ENV_ENTRIES) return false;
  return entries.every(
    ([key, entry]) =>
      isEnvName(key) &&
      typeof entry === "string" &&
      entry.length <= MAX_TERMINAL_ENV_VALUE_LENGTH &&
      !entry.includes("\0"),
  );
}

/** Base64 without `Buffer`, so the same helper works in the renderer. */
export function bytesToBase64(bytes: Uint8Array): string {
  let binary = "";
  // 32 KiB per call stays well below the argument-count limit of fromCharCode.
  const chunk = 0x8000;
  for (let offset = 0; offset < bytes.length; offset += chunk) {
    binary += String.fromCharCode(...bytes.subarray(offset, offset + chunk));
  }
  return btoa(binary);
}

/** Inverse of {@link bytesToBase64}; throws on a malformed payload (never silent). */
export function base64ToBytes(value: string): Uint8Array {
  const binary = atob(value);
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index += 1) {
    bytes[index] = binary.charCodeAt(index);
  }
  return bytes;
}

/** Size of the encoded chunk a {@link TerminalDataEvent} will carry. */
export function terminalChunkBase64Length(bytes: number): number {
  return Math.ceil(bytes / 3) * 4;
}
