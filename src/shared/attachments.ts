/**
 * Attachment contracts shared by the renderer, main process, and host.
 *
 * This module deliberately contains neither file bytes nor SDK/Electron types.
 * A representation describes what can be delivered, not a provider-native file
 * block: Pi 1.5 accepts only text and images. Capability checks here are useful
 * for planning, but the session host must revalidate ownership, bytes, approval,
 * budgets, model and run state immediately before delivery.
 */

