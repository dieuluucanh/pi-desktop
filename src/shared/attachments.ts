function record(value: unknown): Record<string, unknown> | null {
  return value !== null && typeof value === "object" && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

/** Strictly validate the new method; do not accept paths, bytes, or extra keys. */
export function validateAttachmentPromptRequest(value: unknown): AttachmentRequestValidation {
  const input = record(value);
  if (!input) return { ok: false, reason: "bad_request" };
  const keys = Object.keys(input);
  if (
    keys.length !== 5 ||
    !keys.every((key) => ["version", "planId", "turnId", "attemptId", "text"].includes(key))
  ) {
    return { ok: false, reason: "bad_request" };
  }
  if (input.version !== ATTACHMENT_DELIVERY_VERSION) {
    return { ok: false, reason: "unsupported_version" };
  }
  if (
    !isAttachmentId(input.planId) ||
    !isAttachmentId(input.turnId) ||
    !isAttachmentId(input.attemptId) ||
    typeof input.text !== "string" ||
    !isWellFormedAttachmentText(input.text)
  ) {
    return { ok: false, reason: "bad_request" };
  }
  return {
    ok: true,
    value: {
      version: ATTACHMENT_DELIVERY_VERSION,
      planId: input.planId,
      turnId: input.turnId,
      attemptId: input.attemptId,
      text: input.text,
    },
  };
}

/** Validate host-reported preparation metadata; bytes are revalidated separately. */
export function validateAttachmentImagePreparationDescription(
  value: unknown,
): AttachmentImagePreparationDescription | null {
  const description = record(value);
  const thumbnail = description?.thumbnail === null ? null : record(description?.thumbnail);
  const digest = (item: unknown): item is string =>
    typeof item === "string" && /^[0-9a-f]{64}$/.test(item);
  const imageMime = (item: unknown): item is string =>
    typeof item === "string" &&
    ["image/png", "image/jpeg", "image/gif", "image/webp"].includes(item);
  const dimension = (item: unknown, maximum: number): item is number =>
    Number.isSafeInteger(item) && Number(item) > 0 && Number(item) <= maximum;
  if (
    !description ||
    Object.keys(description).length !== 8 ||
    !Object.keys(description).every((key) =>
      [
        "sha256",
        "bytes",
        "mimeType",
        "width",
        "height",
        "originalWidth",
        "originalHeight",
        "thumbnail",
      ].includes(key),
    ) ||
    !digest(description.sha256) ||
    !Number.isSafeInteger(description.bytes) ||
    Number(description.bytes) <= 0 ||
    Number(description.bytes) > ATTACHMENT_LIMITS.imageOriginalBytes ||
    !imageMime(description.mimeType) ||
    !dimension(description.width, 32_768) ||
    !dimension(description.height, 32_768) ||
    !dimension(description.originalWidth, 32_768) ||
    !dimension(description.originalHeight, 32_768) ||
    Number(description.width) > Number(description.originalWidth) ||
    Number(description.height) > Number(description.originalHeight) ||
    (description.thumbnail !== null &&
      (!thumbnail ||
        Object.keys(thumbnail).length !== 5 ||
        !Object.keys(thumbnail).every((key) =>
          ["sha256", "bytes", "mimeType", "width", "height"].includes(key),
        ) ||
        !digest(thumbnail.sha256) ||
        !Number.isSafeInteger(thumbnail.bytes) ||
        Number(thumbnail.bytes) <= 0 ||
        Number(thumbnail.bytes) > ATTACHMENT_LIMITS.previewBytes ||
        !imageMime(thumbnail.mimeType) ||
        !dimension(thumbnail.width, ATTACHMENT_LIMITS.thumbnailMaxDimension) ||
        !dimension(thumbnail.height, ATTACHMENT_LIMITS.thumbnailMaxDimension)))
  )
    return null;
  return {
    sha256: description.sha256,
    bytes: Number(description.bytes),
    mimeType: description.mimeType,
    width: Number(description.width),
    height: Number(description.height),
    originalWidth: Number(description.originalWidth),
    originalHeight: Number(description.originalHeight),
    thumbnail: thumbnail
      ? {
          sha256: thumbnail.sha256 as string,
          bytes: Number(thumbnail.bytes),
          mimeType: thumbnail.mimeType as string,
          width: Number(thumbnail.width),
          height: Number(thumbnail.height),
        }
      : null,
  };
}

/** Strictly validate a persisted classification record (store authority only). */
export function validateAttachmentClassification(value: unknown): AttachmentClassification | null {
  const input = record(value);
  const text = input?.text === null ? null : record(input?.text);
  const image = input?.image === null ? null : record(input?.image);
  const label = (item: unknown, maximum = 512): item is string =>
    typeof item === "string" &&
    item.length > 0 &&
    item.length <= maximum &&
    Array.from(item).every((character) => {
      const code = character.charCodeAt(0);
      return code >= 32 && code !== 127;
    });
  const countValue = (item: unknown): item is number =>
    Number.isSafeInteger(item) && Number(item) >= 0;
  const reason = (item: unknown): item is AttachmentReason =>
    typeof item === "string" && CLASSIFICATION_FAILURE_REASONS.includes(item as AttachmentReason);
  if (
    !input ||
    Object.keys(input).length !== 8 ||
    !Object.keys(input).every((key) =>
      [
        "version",
        "kind",
        "format",
        "detectedMime",
        "warnings",
        "text",
        "image",
        "failure",
      ].includes(key),
    ) ||
    input.version !== ATTACHMENT_CLASSIFICATION_VERSION ||
    !["text", "image", "document", "unsupported", "failed"].includes(String(input.kind)) ||
    !(input.format === null || label(input.format, 64)) ||
    !(input.detectedMime === null || label(input.detectedMime, 255)) ||
    !Array.isArray(input.warnings) ||
    input.warnings.length > 64 ||
    !input.warnings.every((warning) => label(warning)) ||
    !(input.failure === null || reason(input.failure)) ||
    (text !== null &&
      (Object.keys(text).length !== 2 ||
        !Object.keys(text).every((key) => ["promptBytes", "empty"].includes(key)) ||
        !countValue(text.promptBytes) ||
        Number(text.promptBytes) > ATTACHMENT_LIMITS.documentOriginalBytes ||
        typeof text.empty !== "boolean")) ||
    (image !== null &&
      (Object.keys(image).length !== 3 ||
        !Object.keys(image).every((key) => ["width", "height", "animated"].includes(key)) ||
        !countValue(image.width) ||
        Number(image.width) <= 0 ||
        !countValue(image.height) ||
        Number(image.height) <= 0 ||
        Number(image.width) * Number(image.height) > ATTACHMENT_LIMITS.imagePixels ||
        typeof image.animated !== "boolean"))
  )
    return null;
  const kind = input.kind as AttachmentClassification["kind"];
  if (kind === "text" && (!text || image !== null || input.failure !== null)) return null;
  if (kind === "image" && (!image || text !== null || input.failure !== null)) return null;
  if (kind === "document" && (text !== null || image !== null || input.failure !== null))
    return null;
  if ((kind === "unsupported" || kind === "failed") && (!input.failure || text || image))
    return null;
  return {
    version: ATTACHMENT_CLASSIFICATION_VERSION,
    kind,
    format: input.format as string | null,
    detectedMime: input.detectedMime as string | null,
    warnings: [...(input.warnings as string[])],
    text: text ? { promptBytes: Number(text.promptBytes), empty: text.empty as boolean } : null,
    image: image
      ? {
          width: Number(image.width),
          height: Number(image.height),
          animated: image.animated as boolean,
        }
      : null,
    failure: input.failure as AttachmentReason | null,
  };
}

/** Reasons a classification failure record may carry. */
export const CLASSIFICATION_FAILURE_REASONS: readonly AttachmentReason[] = [
  "format_unsupported",
  "format_mismatch",
  "original_too_large",
  "classification_failed",
];

function boundedLabel(value: unknown, maximum = 512): value is string {
  return (
    typeof value === "string" &&
    value.length > 0 &&
    value.length <= maximum &&
    Array.from(value).every((character) => {
      const code = character.charCodeAt(0);
      return code >= 32 && code !== 127;
    })
  );
}

function validateSubmissionDisplay(value: unknown): AttachmentSubmissionDisplay | null {
  const display = record(value);
  const coverage = record(display?.coverage);
  const image = display?.image === null ? null : record(display?.image);
  if (
    !display ||
    Object.keys(display).length !== 9 ||
    !Object.keys(display).every((key) =>
      [
        "name",
        "originalKind",
        "originalBytes",
        "representationBytes",
        "origin",
        "preparationVersion",
        "warnings",
        "coverage",
        "image",
      ].includes(key),
    ) ||
    !boundedLabel(display.name, 255) ||
    display.name.includes("/") ||
    display.name.includes("\\") ||
    (display.originalKind !== "text" && display.originalKind !== "image") ||
    !Number.isSafeInteger(display.originalBytes) ||
    Number(display.originalBytes) < 0 ||
    Number(display.originalBytes) > ATTACHMENT_LIMITS.draftOriginalBytes ||
    !Number.isSafeInteger(display.representationBytes) ||
    Number(display.representationBytes) < 0 ||
    Number(display.representationBytes) >
      (display.originalKind === "text"
        ? ATTACHMENT_LIMITS.promptTextBytesPerFile
        : ATTACHMENT_LIMITS.imageOriginalBytes) ||
    (display.origin !== "direct" && display.origin !== "converted") ||
    !boundedLabel(display.preparationVersion, 128) ||
    !Array.isArray(display.warnings) ||
    display.warnings.length > 64 ||
    display.warnings.some((warning) => !boundedLabel(warning)) ||
    !coverage ||
    Object.keys(coverage).length !== 1 ||
    coverage.kind !== "entire-file" ||
    (display.originalKind === "text" && image !== null) ||
    (display.originalKind === "image" &&
      (!image ||
        Object.keys(image).length !== 3 ||
        !Object.keys(image).every((key) => ["mime", "width", "height"].includes(key)) ||
        !["image/png", "image/jpeg", "image/gif", "image/webp"].includes(String(image.mime)) ||
        !Number.isSafeInteger(image.width) ||
        Number(image.width) <= 0 ||
        Number(image.width) > 8192 ||
        !Number.isSafeInteger(image.height) ||
        Number(image.height) <= 0 ||
        Number(image.height) > 8192))
  )
    return null;
  return {
    name: display.name,
    originalKind: display.originalKind,
    originalBytes: Number(display.originalBytes),
    representationBytes: Number(display.representationBytes),
    origin: display.origin,
    preparationVersion: display.preparationVersion,
    warnings: [...display.warnings] as string[],
    coverage: { kind: "entire-file" },
    image: image
      ? {
          mime: image.mime as string,
          width: Number(image.width),
          height: Number(image.height),
        }
      : null,
  };
}

