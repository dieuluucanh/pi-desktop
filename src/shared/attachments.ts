/** Validate renderer-safe card metadata received with session history. */
export function validateAttachmentTranscriptCard(value: unknown): AttachmentTranscriptCard | null {
  const card = record(value);
  if (
    !card ||
    Object.keys(card).length !== 6 ||
    !Object.keys(card).every((key) =>
      ["version", "status", "associationEntryId", "userEntryId", "turnId", "files"].includes(key),
    ) ||
    card.version !== 1 ||
    card.status !== "submitted" ||
    !boundedLabel(card.associationEntryId) ||
    !boundedLabel(card.userEntryId) ||
    !isAttachmentId(card.turnId) ||
    !Array.isArray(card.files) ||
    card.files.length === 0 ||
    card.files.length > ATTACHMENT_LIMITS.filesPerDraft
  )
    return null;
  const files = card.files.map((value) => {
    const file = record(value);
    if (
      !file ||
      (Object.keys(file).length !== 3 && Object.keys(file).length !== 4) ||
      !Object.keys(file).every((key) =>
        ["representationId", "originalId", "modality", "display"].includes(key),
      ) ||
      !isAttachmentId(file.representationId) ||
      !isAttachmentId(file.originalId) ||
      (file.modality !== "text" && file.modality !== "image")
    )
      return null;
    const display =
      file.display === undefined ? undefined : validateSubmissionDisplay(file.display);
    if (file.display !== undefined && display === null) return null;
    if (
      display &&
      ((file.modality === "text" && display.originalKind !== "text") ||
        (file.modality === "image" && display.originalKind !== "image"))
    )
      return null;
    return {
      representationId: file.representationId,
      originalId: file.originalId,
      modality: file.modality,
      ...(display ? { display } : {}),
    } as AttachmentTranscriptFile;
  });
  if (
    files.some((file) => file === null) ||
    new Set(files.map((file) => file?.representationId)).size !== files.length
  )
    return null;
  return {
    version: 1,
    status: "submitted",
    associationEntryId: card.associationEntryId,
    userEntryId: card.userEntryId,
    turnId: card.turnId,
    files: files as AttachmentTranscriptFile[],
  };
}

/** Validate metadata read back from a persisted SDK custom entry. */
export function validateAttachmentSubmissionMetadata(
  value: unknown,
): AttachmentSubmissionMetadata | null {
  const input = record(value);
  if (
    !input ||
    Object.keys(input).length !== 11 ||
    !Object.keys(input).every((key) =>
      [
        "version",
        "planId",
        "turnId",
        "attemptId",
        "scope",
        "sourceTextSha256",
        "userEntryId",
        "textSha256",
        "images",
        "representations",
        "createdAt",
      ].includes(key),
    ) ||
    input.version !== 1 ||
    !isAttachmentId(input.planId) ||
    !isAttachmentId(input.turnId) ||
    !isAttachmentId(input.attemptId) ||
    typeof input.sourceTextSha256 !== "string" ||
    !/^[0-9a-f]{64}$/.test(input.sourceTextSha256) ||
    !boundedLabel(input.userEntryId) ||
    typeof input.textSha256 !== "string" ||
    !/^[0-9a-f]{64}$/.test(input.textSha256) ||
    !Number.isSafeInteger(input.createdAt) ||
    Number(input.createdAt) < 0 ||
    !Array.isArray(input.images) ||
    input.images.length > ATTACHMENT_LIMITS.filesPerDraft ||
    !Array.isArray(input.representations) ||
    input.representations.length === 0 ||
    input.representations.length > ATTACHMENT_LIMITS.filesPerDraft
  )
    return null;
  const scope = record(input.scope);
  if (
    !scope ||
    Object.keys(scope).length !== 11 ||
    !Object.keys(scope).every((key) =>
      [
        "authorityId",
        "leaseId",
        "profileKey",
        "tabId",
        "draftId",
        "hostGeneration",
        "processGeneration",
        "sessionId",
        "sessionEpoch",
        "branchId",
        "revision",
      ].includes(key),
    ) ||
    !isAttachmentId(scope.authorityId) ||
    !isAttachmentId(scope.leaseId) ||
    typeof scope.profileKey !== "string" ||
    !/^[0-9a-f]{64}$/.test(scope.profileKey) ||
    !boundedLabel(scope.tabId, 128) ||
    !isAttachmentId(scope.draftId) ||
    !Number.isSafeInteger(scope.hostGeneration) ||
    Number(scope.hostGeneration) < 0 ||
    !Number.isSafeInteger(scope.processGeneration) ||
    Number(scope.processGeneration) <= 0 ||
    !boundedLabel(scope.sessionId) ||
    !Number.isSafeInteger(scope.sessionEpoch) ||
    Number(scope.sessionEpoch) <= 0 ||
    !(scope.branchId === null || boundedLabel(scope.branchId)) ||
    !boundedLabel(scope.revision)
  )
    return null;
  const images = input.images.map((item) => {
    const image = record(item);
    if (
      !image ||
      Object.keys(image).length !== 2 ||
      !Object.keys(image).every((key) => ["mimeType", "sha256"].includes(key)) ||
      !["image/png", "image/jpeg", "image/gif", "image/webp"].includes(String(image.mimeType)) ||
      typeof image.sha256 !== "string" ||
      !/^[0-9a-f]{64}$/.test(image.sha256)
    )
      return null;
    return { mimeType: image.mimeType as string, sha256: image.sha256 };
  });
  if (images.some((image) => image === null)) return null;
  const representations = input.representations.map((item) => {
    const representation = record(item);
    if (
      !representation ||
      (Object.keys(representation).length !== 5 && Object.keys(representation).length !== 6) ||
      !Object.keys(representation).every((key) =>
        [
          "representationId",
          "representationSha256",
          "originalId",
          "originalSha256",
          "modality",
          "display",
        ].includes(key),
      ) ||
      !isAttachmentId(representation.representationId) ||
      typeof representation.representationSha256 !== "string" ||
      !/^[0-9a-f]{64}$/.test(representation.representationSha256) ||
      !isAttachmentId(representation.originalId) ||
      typeof representation.originalSha256 !== "string" ||
      !/^[0-9a-f]{64}$/.test(representation.originalSha256) ||
      (representation.modality !== "text" && representation.modality !== "image")
    )
      return null;
    const display =
      representation.display === undefined
        ? undefined
        : validateSubmissionDisplay(representation.display);
    if (representation.display !== undefined && display === null) return null;
    if (
      display &&
      ((representation.modality === "text" && display.originalKind !== "text") ||
        (representation.modality === "image" && display.originalKind !== "image"))
    )
      return null;
    const validated = {
      representationId: representation.representationId,
      representationSha256: representation.representationSha256,
      originalId: representation.originalId,
      originalSha256: representation.originalSha256,
      modality: representation.modality,
    };
    return display ? { ...validated, display } : validated;
  });
  if (
    representations.some((representation) => representation === null) ||
    new Set(representations.map((representation) => representation?.representationId)).size !==
      representations.length
  )
    return null;
  return {
    version: 1,
    planId: input.planId,
    turnId: input.turnId,
    attemptId: input.attemptId,
    scope: {
      authorityId: scope.authorityId,
      leaseId: scope.leaseId,
      profileKey: scope.profileKey,
      tabId: scope.tabId,
      draftId: scope.draftId,
      hostGeneration: Number(scope.hostGeneration),
      processGeneration: Number(scope.processGeneration),
      sessionId: scope.sessionId,
      sessionEpoch: Number(scope.sessionEpoch),
      branchId: scope.branchId as string | null,
      revision: scope.revision,
    },
    sourceTextSha256: input.sourceTextSha256,
    userEntryId: input.userEntryId,
    textSha256: input.textSha256,
    images: images as AttachmentSubmissionImageDigest[],
    representations: representations as AttachmentSubmissionRepresentation[],
    createdAt: Number(input.createdAt),
  };
}

