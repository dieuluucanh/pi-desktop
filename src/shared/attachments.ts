const OPAQUE_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

export function isAttachmentId(value: unknown): value is AttachmentId {
  return typeof value === "string" && OPAQUE_ID.test(value);
}

/** Providers sanitize lone UTF-16 surrogates; never approve text they will rewrite. */
export function isWellFormedAttachmentText(text: string): boolean {
  for (const character of text) {
    const codePoint = character.codePointAt(0) ?? 0;
    if (codePoint >= 0xd800 && codePoint <= 0xdfff) return false;
  }
  return true;
}

