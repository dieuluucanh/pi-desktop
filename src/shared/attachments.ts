/**
 * Identity/hash/modality only. Presentation fields (`display`) may be added or
 * improved across app versions without changing delivery authorization, proof
 * matching, or recovery. Order is significant: it mirrors the approved plan.
 */
export function attachmentRepresentationIdentity(
  representation: AttachmentSubmissionRepresentation,
): AttachmentSubmissionRepresentation {
  return {
    representationId: representation.representationId,
    representationSha256: representation.representationSha256,
    originalId: representation.originalId,
    originalSha256: representation.originalSha256,
    modality: representation.modality,
  };
}

/** Compare ordered representation identities, ignoring optional display metadata. */
export function sameAttachmentRepresentations(
  left: readonly AttachmentSubmissionRepresentation[],
  right: readonly AttachmentSubmissionRepresentation[],
): boolean {
  if (left.length !== right.length) return false;
  for (let index = 0; index < left.length; index++) {
    const a = left[index];
    const b = right[index];
    if (
      !a ||
      !b ||
      a.representationId !== b.representationId ||
      a.representationSha256 !== b.representationSha256 ||
      a.originalId !== b.originalId ||
      a.originalSha256 !== b.originalSha256 ||
      a.modality !== b.modality
    )
      return false;
  }
  return true;
}

/** Missing, disabled, malformed, and newer host capabilities all fail closed. */
export function hostSupportsAttachmentDelivery(capabilities: unknown): boolean {
  return record(capabilities)?.attachmentDeliveryVersion === ATTACHMENT_DELIVERY_VERSION;
}

const TRANSITIONS: Record<AttachmentStatus, readonly AttachmentStatus[]> = {
  importing: ["classifying", "failed", "removed"],
  classifying: ["ready", "needs_conversion", "blocked", "failed", "removed"],
  needs_conversion: ["converting", "blocked", "removed"],
  converting: ["awaiting_approval", "needs_conversion", "failed", "removed"],
  awaiting_approval: ["ready", "converting", "needs_conversion", "blocked", "removed"],
  ready: ["submitting", "converting", "needs_conversion", "blocked", "removed"],
  blocked: ["ready", "needs_conversion", "converting", "failed", "removed"],
  failed: ["importing", "classifying", "needs_conversion", "converting", "removed"],
  submitting: ["accepted", "retained_for_retry"],
  accepted: [],
  retained_for_retry: ["ready", "blocked", "removed"],
  removed: [],
};

export function canTransitionAttachment(from: AttachmentStatus, to: AttachmentStatus): boolean {
  return TRANSITIONS[from].includes(to);
}

function nonNegativeInteger(value: unknown): value is number {
  return typeof value === "number" && Number.isSafeInteger(value) && value >= 0;
}

/**
 * Resolve only SDK-supported input modalities against the session's actual
 * model. Binary document blocks remain unsupported even if a provider has a
 * broader native API. Model input limits are copied, never inferred as infinite.
 */
export function resolveAttachmentCapability(
  modelValue: unknown,
  modality: AttachmentModality,
): AttachmentCapability {
  if (modality === "document") return { state: "unsupported", reason: "sdk_document_unsupported" };
  const model = record(modelValue);
  if (
    !model ||
    typeof model.provider !== "string" ||
    model.provider.length === 0 ||
    typeof model.id !== "string" ||
    model.id.length === 0 ||
    typeof model.api !== "string" ||
    model.api.length === 0 ||
    (model.type !== undefined && model.type !== "chat") ||
    !Array.isArray(model.input) ||
    !model.input.every((item: unknown) => item === "text" || item === "image")
  ) {
    return { state: "unknown", reason: "model_unknown" };
  }
  if (!model.input.includes(modality)) {
    return { state: "unsupported", reason: "model_modality_unsupported" };
  }

  const inputLimits = model.inputLimits === undefined ? {} : record(model.inputLimits);
  const images = inputLimits?.images === undefined ? {} : record(inputLimits.images);
  const resize = images?.resize === undefined ? {} : record(images.resize);
  if (!inputLimits || !images || !resize) {
    return { state: "unknown", reason: "model_limits_unknown" };
  }
  const values = [
    inputLimits.maxRequestBytes,
    images.maxPerMessage,
    images.maxPerRequest,
    resize.maxBytes,
    resize.maxWidth,
    resize.maxHeight,
  ];
  if (values.some((value) => value !== undefined && !nonNegativeInteger(value))) {
    return { state: "unknown", reason: "model_limits_unknown" };
  }
  return {
    state: "supported",
    model: { provider: model.provider, id: model.id, api: model.api },
    limits: {
      maxRequestBytes: (inputLimits.maxRequestBytes as number | undefined) ?? null,
      maxImagesPerMessage: (images.maxPerMessage as number | undefined) ?? null,
      maxImagesPerRequest: (images.maxPerRequest as number | undefined) ?? null,
      maxImageBytes: (resize.maxBytes as number | undefined) ?? null,
      maxImageWidth: (resize.maxWidth as number | undefined) ?? null,
      maxImageHeight: (resize.maxHeight as number | undefined) ?? null,
    },
  };
}

/** Evaluate representation format and consent separately from model capability. */
export function attachmentRepresentationReason(input: {
  originalKind: AttachmentOriginalKind;
  modality: AttachmentModality;
  origin: AttachmentRepresentationOrigin;
  approved: boolean;
}): AttachmentReason | null {
  const { originalKind, modality, origin, approved } = input;
  if (originalKind === "audio" || originalKind === "video" || originalKind === "other") {
    return "format_unsupported";
  }
  if (modality === "document") return "sdk_document_unsupported";
  const document = ["pdf", "word", "spreadsheet", "presentation"].includes(originalKind);
  if (document && (origin !== "converted" || modality !== "text")) return "conversion_required";
  if (!document && modality !== originalKind) return "format_unsupported";
  if (origin === "converted" && !approved) return "approval_required";
  return null;
}

export interface AttachmentBudgetInput {
  originalKind: AttachmentOriginalKind;
  originalBytes: number;
  draftOriginalBytes: number;
  fileCount: number;
  textBytes: number;
  totalTextBytes: number;
  estimatedTokens: number;
  availableTokens: number;
}

/** Checks application ceilings; callers must additionally enforce provider limits. */
export function attachmentBudgetReason(input: AttachmentBudgetInput): AttachmentReason | null {
  const amounts = [
    input.originalBytes,
    input.draftOriginalBytes,
    input.fileCount,
    input.textBytes,
    input.totalTextBytes,
    input.estimatedTokens,
    input.availableTokens,
  ];
  if (
    amounts.some((amount) => !nonNegativeInteger(amount)) ||
    input.fileCount < 1 ||
    input.draftOriginalBytes < input.originalBytes ||
    input.totalTextBytes < input.textBytes
  ) {
    return "invalid_budget";
  }
  if (input.fileCount > ATTACHMENT_LIMITS.filesPerDraft) return "too_many_files";
  if (input.draftOriginalBytes > ATTACHMENT_LIMITS.draftOriginalBytes) return "draft_too_large";
  const maxOriginal =
    input.originalKind === "text"
      ? ATTACHMENT_LIMITS.textOriginalBytes
      : input.originalKind === "image"
        ? ATTACHMENT_LIMITS.imageOriginalBytes
        : ATTACHMENT_LIMITS.documentOriginalBytes;
  if (input.originalBytes > maxOriginal) return "original_too_large";
  if (
    input.textBytes > ATTACHMENT_LIMITS.promptTextBytesPerFile ||
    input.totalTextBytes > ATTACHMENT_LIMITS.promptTextBytesTotal
  ) {
    return "text_limit_exceeded";
  }
  if (
    input.estimatedTokens > ATTACHMENT_LIMITS.promptTextEstimatedTokens ||
    input.estimatedTokens > input.availableTokens
  ) {
    return "context_limit_exceeded";
  }
  return null;
}
