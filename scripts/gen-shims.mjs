#!/usr/bin/env node
/**
 * Generate the PATH shims that let extensions shell out to `pi`, `node`, `npm`
 * and `npx` without any global install (plan D16, risk R4).
 *
 *   npm run runtime:shims                      # dev shims for this machine
 *   node scripts/gen-shims.mjs --platform linux-x64
 *   node scripts/gen-shims.mjs --mode packaged --runtime-dir <resources>/runtime
 *
 * Layout assumed (matches src/main/runtime/layout.ts):
 *   <runtime>/bin/pi            -> <runtime>/node/<platform>-<arch>/{bin/,}node + out/host/index.mjs
 *   <runtime>/bin/npm           -> ... + node_modules/npm/bin/npm-cli.js
 *
 * Every shim honours `PI_DESKTOP_NODE` and `PI_DESKTOP_HOST_ENTRY`, so the app's
 * supervisor can point a host at an exact runtime without touching the files.
 */

import { chmod, mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { parseArgs } from "node:util";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Every shim name any platform has ever used; anything not written is pruned. */
const KNOWN_SHIMS = ["pi", "pi.cmd", "node", "node.cmd", "npm", "npm.cmd", "npx", "npx.cmd"];

function fail(message) {
  process.stderr.write(`gen-shims: ${message}\n`);
  process.exit(1);
}

function hostTarget() {
  const arch = process.arch === "arm64" ? "arm64" : "x64";
  return `${process.platform}-${arch}`;
}

/** Windows puts node at the root of the distribution; everywhere else in bin/. */
function nodeRelative(target) {
  return target.startsWith("win32") ? "node.exe" : "bin/node";
}

function npmCliRelative(target) {
  return target.startsWith("win32")
    ? "node_modules/npm/bin/npm-cli.js"
    : "lib/node_modules/npm/bin/npm-cli.js";
}

function npxCliRelative(target) {
  return target.startsWith("win32")
    ? "node_modules/npm/bin/npx-cli.js"
    : "lib/node_modules/npm/bin/npx-cli.js";
}

function posix(path) {
  return path.split(sep).join("/");
}

/**
 * `$0` resolution that uses shell builtins only.
 *
 * The shim directory is *meant* to be the whole PATH for a host process (plan
 * D16) and `runtime:verify` proves it by running the shims with nothing else on
 * PATH — where `dirname` does not exist, so a `dirname`-based prologue fails with
 * "dirname: not found" and exits 127. `${0%/*}`, `command -v`, `cd` and `pwd` are
 * all builtins in every POSIX shell, so this works with an empty PATH.
 */
const unixDirPrologue = `# Resolve this shim's own directory with shell builtins only: PATH may contain
# nothing but this directory, so \`dirname\` is not available.
SELF=$0
case "$SELF" in
  */*) ;;
  *) SELF=$(command -v -- "$SELF" 2>/dev/null) || SELF="" ;;
esac
case "$SELF" in
  */*) DIR=$(CDPATH= cd -- "\${SELF%/*}" && pwd) ;;
  *)
    echo "pi-desktop shim: cannot locate its own directory" >&2
    exit 127
    ;;
esac`;

/**
 * @returns {{ name: string, content: string }[]} shim files to write
 */
function buildShims({ target, binDir, entry, mode }) {
  const nodeFromBin = posix(
    relative(binDir, join(binDir, "..", "node", target, nodeRelative(target))),
  );
  const npmCli = posix(
    relative(binDir, join(binDir, "..", "node", target, npmCliRelative(target))),
  );
  const npxCli = posix(
    relative(binDir, join(binDir, "..", "node", target, npxCliRelative(target))),
  );
  const entryFromBin = posix(relative(binDir, entry));
  const nodeWin = nodeFromBin.split("/").join("\\");
  const entryWin = entryFromBin.split("/").join("\\");
  const npmWin = npmCli.split("/").join("\\");
  const npxWin = npxCli.split("/").join("\\");

  const unixBody = (script) => `#!/bin/sh
# Generated by scripts/gen-shims.mjs (${mode}) — do not edit.
${unixDirPrologue}
NODE="\${PI_DESKTOP_NODE:-$DIR/${nodeFromBin}}"
${script}
`;

  const windowsBody = (name, script) => `@echo off
rem Generated by scripts/gen-shims.mjs (${mode}) - do not edit.
setlocal
set "DIR=%~dp0"
rem When cmd starts a .cmd by bare name through PATH, %~dp0 is the current
rem directory, not this file's directory. If the bundled node is not beside
rem %DIR%, locate this shim on PATH instead. PI_DESKTOP_NODE may be stripped by
rem tools such as Turbo, so this path must not depend on it.
set "SELF="
if not exist "%DIR%${nodeWin}" for %%I in (${name}) do set "SELF=%%~$PATH:I"
if defined SELF for %%I in ("%SELF%") do set "DIR=%%~dpI"
set "NODE=%DIR%${nodeWin}"
if defined PI_DESKTOP_NODE set "NODE=%PI_DESKTOP_NODE%"
if not defined PI_DESKTOP_NODE if not exist "%NODE%" (
  echo pi-desktop shim: bundled Node not found at "%NODE%" 1>&2
  exit /b 127
)
${script}
`;

  const piUnix = unixBody(`ENTRY="\${PI_DESKTOP_HOST_ENTRY:-$DIR/${entryFromBin}}"
exec "$NODE" "$ENTRY" "$@"`);
  const piWindows = windowsBody(
    "pi.cmd",
    `set "ENTRY=%DIR%${entryWin}"
if defined PI_DESKTOP_HOST_ENTRY set "ENTRY=%PI_DESKTOP_HOST_ENTRY%"
"%NODE%" "%ENTRY%" %*
exit /b %ERRORLEVEL%`,
  );

  const isWindowsTarget = target.startsWith("win32");

  return [
    { name: "pi", content: piUnix },
    ...(isWindowsTarget ? [{ name: "pi.cmd", content: piWindows }] : []),
    { name: "node", content: unixBody(`exec "$NODE" "$@"`) },
    {
      name: "npm",
      content: unixBody(`exec "$NODE" "$DIR/${npmCli}" "$@"`),
    },
    ...(isWindowsTarget
      ? [
          {
            name: "npm.cmd",
            content: windowsBody("npm.cmd", `"%NODE%" "%DIR%${npmWin}" %*\nexit /b %ERRORLEVEL%`),
          },
        ]
      : []),
    {
      name: "npx",
      content: unixBody(`exec "$NODE" "$DIR/${npxCli}" "$@"`),
    },
    ...(isWindowsTarget
      ? [
          {
            name: "npx.cmd",
            content: windowsBody("npx.cmd", `"%NODE%" "%DIR%${npxWin}" %*\nexit /b %ERRORLEVEL%`),
          },
        ]
      : []),
  ];
}

async function main() {
  const { values } = parseArgs({
    options: {
      platform: { type: "string", default: hostTarget() },
      mode: { type: "string", default: "dev" },
      out: { type: "string" },
      "runtime-dir": { type: "string" },
      "app-root": { type: "string" },
      quiet: { type: "boolean", default: false },
    },
    allowPositionals: false,
  });

  const target = values.platform;
  if (values.mode !== "dev" && values.mode !== "packaged") {
    fail(`unknown --mode "${values.mode}" (expected dev or packaged)`);
  }

  const runtimeDir = resolve(values["runtime-dir"] ?? join(repoRoot, "resources", "runtime"));
  const binDir = resolve(values.out ?? join(runtimeDir, "bin"));

  // In a packaged build the host entry lives next to the asar inside resources:
  //   <resources>/runtime/bin  ->  <resources>/app.asar.unpacked/out/host/index.mjs
  const entry =
    values.mode === "packaged"
      ? join(
          resolve(values["app-root"] ?? dirname(runtimeDir)),
          "app.asar.unpacked",
          "out",
          "host",
          "index.mjs",
        )
      : join(repoRoot, "out", "host", "index.mjs");

  const shims = buildShims({ target, binDir, entry, mode: values.mode });
  await mkdir(binDir, { recursive: true });

  const written = new Set(shims.map((shim) => shim.name));
  const pruned = [];
  for (const name of KNOWN_SHIMS) {
    if (written.has(name)) continue;
    await rm(join(binDir, name), { force: true });
    pruned.push(name);
  }

  for (const shim of shims) {
    const destination = join(binDir, shim.name);
    await writeFile(destination, shim.content, "utf8");
    if (!shim.name.endsWith(".cmd")) await chmod(destination, 0o755);
  }

  if (!values.quiet) {
    const prunedNote = pruned.length > 0 ? `; pruned ${pruned.join(", ")}` : "";
    process.stderr.write(
      `gen-shims: wrote ${shims.length} shims to ${relative(repoRoot, binDir) || binDir} (${target}, ${values.mode}${prunedNote})\n`,
    );
  }
}

await main();
