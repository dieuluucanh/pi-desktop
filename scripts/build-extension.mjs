#!/usr/bin/env node
/**
 * Build the terminal-Pi checkpoint extension (git-checkpoint plan step 26).
 *
 *   npm run build:extension
 *
 * Produces `dist/pi-checkpoints/`:
 *
 *   index.mjs      the bundled extension (no `@earendil-works`, no `node_modules`)
 *   package.json   with `pi.extensions: ["./index.mjs"]` — the field Pi reads
 *   README.md      install and usage notes
 *
 * The artifact exists so the *same* checkpoint code that Pi Desktop auto-loads
 * can be installed into a terminal Pi. For development/test, install the path
 * artifact; for users, install the published package:
 *
 *   pi install path:<abs path>/dist/pi-checkpoints
 *   pi install npm:@dieulc/checkpoints
 *
 * **No publish step and no RECOMMENDED_PACKAGES entry.** Publication is a
 * separate release decision, and an entry that resolved to nothing would be a
 * lie. `dist/` is already gitignored.
 *
 * The bundling policy is deliberately the same as `vite.host.config.ts`:
 * relative imports are inlined, bare specifiers stay external. The extension is
 * written so all of its imports *are* relative (see its own doc comment), which
 * is what makes the artifact self-contained.
 */

import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(repoRoot, "dist", "pi-checkpoints");

/** The package name the artifact installs under. */
export const ARTIFACT_PACKAGE_NAME = "@dieulc/checkpoints";

/** The manifest fields Pi's loader reads, plus what a human needs. */
function manifest(version) {
  return {
    name: ARTIFACT_PACKAGE_NAME,
    version,
    private: true,
    description:
      "Folder checkpoints and /rewind for Pi: shadow-git snapshots that work in any folder, git repository or not.",
    license: "MIT",
    type: "module",
    // The field `readPiManifest` / Pi's own loader reads.
    pi: { extensions: ["./index.mjs"] },
    keywords: ["pi-package", "pi-extension", "checkpoints", "rewind", "git"],
  };
}

const README = `# @dieulc/checkpoints

Folder checkpoints for Pi, plus a \`/rewind\` command.

A checkpoint is a snapshot of a whole folder — an Office document, a pile of
images, a code checkout — taken into a **shadow git repository** under your Pi
profile. The project's own \`.git\` is never read or written, so this works in a
folder that has no repository at all.

## Install

Pi Desktop already bundles this extension; terminal Pi users can install the
published package. The path form is for a development checkout.

\`\`\`bash
pi install npm:@dieulc/checkpoints
# or, from this directory:
pi install path:<absolute path to this directory>
\`\`\`

Requires \`git\` on your \`PATH\`. Without git the extension stays silent and Pi
Desktop's rail shows an explicit "checkpoints need git" state.

## What it does

- One snapshot per user prompt, taken before the prompt is processed (steer and
  follow-up prompts included).
- \`/rewind\` lists this session's checkpoints and can restore **files**, the
  **conversation**, or both. A safety snapshot is taken first, so a rewind is
  itself undoable.

## Where the bytes live

\`<profile>/checkpoints/<folder-name>-<hash>/\` — one bare repository per folder,
shared with Pi Desktop. Retention defaults: 100 checkpoints, 30 days, 2 GB per
folder. \`/rewind\` prunes nothing itself; Pi Desktop's Checkpoints section and
Settings do. A prompt that never gets a turn is kept as an unlinked,
files-only checkpoint rather than being dropped.

Generated by \`npm run build:extension\` in the Pi Desktop repository.
`;

async function main() {
  // A malformed root manifest is a broken checkout, not a user-facing failure:
  // say which file and stop rather than emitting an artifact with no version.
  let rootManifest;
  try {
    rootManifest = JSON.parse(await readFile(join(repoRoot, "package.json"), "utf8"));
  } catch (error) {
    throw new Error("cannot read the root package.json", { cause: error });
  }
  if (typeof rootManifest.version !== "string") {
    throw new Error("the root package.json has no version string");
  }

  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  await build({
    root: repoRoot,
    // A config-less build: this script is the config, so `npm run build:extension`
    // cannot be affected by whatever `vite.config.*` a future step adds.
    configFile: false,
    logLevel: "warn",
    build: {
      ssr: true,
      target: "node22",
      outDir,
      emptyOutDir: false,
      minify: false,
      sourcemap: false,
      lib: {
        entry: resolve(repoRoot, "src/extensions/pi-checkpoints.ts"),
        formats: ["es"],
        fileName: () => "index.mjs",
      },
      rollupOptions: {
        // Bare specifiers are external; relative, absolute and `file:` entries are
        // bundled. The absolute check matters: the *entry* is an absolute path, and
        // treating it as external makes rollup refuse the build outright.
        external: (id) =>
          !id.startsWith(".") && !id.startsWith("/") && !id.startsWith("file:") && !isAbsolute(id),
        output: { entryFileNames: "index.mjs" },
      },
    },
  });

  await writeFile(
    join(outDir, "package.json"),
    `${JSON.stringify(manifest(rootManifest.version), null, 2)}\n`,
    "utf8",
  );
  await writeFile(join(outDir, "README.md"), README, "utf8");

  const stat = await readFile(join(outDir, "index.mjs"), "utf8");
  process.stdout.write(
    `build-extension: ${relative(repoRoot, outDir)}/index.mjs (${stat.length} bytes), ` +
      `package.json, README.md\n`,
  );
  process.stdout.write(`build-extension: install with \`pi install path:${outDir}\`\n`);
}

main().catch((error) => {
  process.stderr.write(`build-extension: ${error instanceof Error ? error.stack : error}\n`);
  process.exit(1);
});
